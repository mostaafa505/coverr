// Helper to create template
function makeTemplate(
  w: number,
  h: number,
  r: number,
  cam: { x: number; y: number; w: number; h: number; r?: number; shape?: 'rect' | 'circle' | 'rounded-rect' },
  extraCutouts: { id: string; name: string; type: any; shape: any; x: number; y: number; w: number; h: number; r?: number }[] = []
) {
  const cutouts = [
    {
      id: 'cam-main',
      name: 'الكاميرا الرئيسية',
      nameAr: 'فتحة الكاميرات',
      type: 'camera' as const,
      shape: cam.shape || ('rounded-rect' as const),
      xMm: cam.x,
      yMm: cam.y,
      widthMm: cam.w,
      heightMm: cam.h,
      radiusMm: cam.r ?? (cam.shape === 'circle' ? cam.w / 2 : 5),
    },
    ...extraCutouts.map((ec) => ({
      id: ec.id,
      name: ec.name,
      nameAr: ec.name,
      type: ec.type,
      shape: ec.shape,
      xMm: ec.x,
      yMm: ec.y,
      widthMm: ec.w,
      heightMm: ec.h,
      radiusMm: ec.r ?? ec.w / 2,
    })),
  ];

  return {
    widthMm: w,
    heightMm: h,
    cornerRadiusMm: r,
    bleedMm: 3.0,
    safeMarginMm: 3.0,
    cutouts,
    version: 1,
    lastUpdated: new Date().toISOString(),
  };
}

